// Regenerates src/soums.data.ts from the OCHA COD-AB spreadsheet for Mongolia.
//
//   1. Download mng_admin_boundaries.xlsx from https://data.humdata.org/dataset/cod-ab-mng
//   2. node scripts/build-soums.mjs path/to/mng_admin_boundaries.xlsx
//
// Names are copied verbatim from the `adm2_name1` (Mongolian) column of the
// `mng_admin2` sheet. Nothing is corrected here: if the source is wrong, fix it
// upstream or document it in the README, don't patch it silently.
import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

const xlsx = process.argv[2];
if (!xlsx) throw new Error("usage: node scripts/build-soums.mjs <mng_admin_boundaries.xlsx>");

// An .xlsx is a zip. bsdtar (Windows, macOS) reads zips; elsewhere fall back to unzip.
const dir = mkdtempSync(join(tmpdir(), "cod-ab-mng-"));
try {
  execFileSync("tar", ["-xf", xlsx, "-C", dir], { stdio: "ignore" });
} catch {
  execFileSync("unzip", ["-q", "-o", xlsx, "-d", dir]);
}

const unescape = (s) =>
  s.replace(/&lt;/g, "<").replace(/&gt;/g, ">").replace(/&quot;/g, '"').replace(/&apos;/g, "'").replace(/&amp;/g, "&");
const read = (p) => readFileSync(join(dir, p), "utf8");

const strings = [...read("xl/sharedStrings.xml").matchAll(/<si>([\s\S]*?)<\/si>/g)].map((m) =>
  unescape([...m[1].matchAll(/<t[^>]*>([\s\S]*?)<\/t>/g)].map((t) => t[1]).join("")),
);

const sheetIndex = [...read("xl/workbook.xml").matchAll(/<sheet name="([^"]+)"/g)].findIndex((m) => m[1] === "mng_admin2");
if (sheetIndex < 0) throw new Error("sheet mng_admin2 not found");

const rows = [...read(`xl/worksheets/sheet${sheetIndex + 1}.xml`).matchAll(/<row[^>]*>([\s\S]*?)<\/row>/g)].map((r) => {
  const row = {};
  for (const c of r[1].matchAll(/<c r="([A-Z]+)\d+"([^>]*?)(?:\/>|>([\s\S]*?)<\/c>)/g)) {
    const v = c[3]?.match(/<v>([\s\S]*?)<\/v>/)?.[1] ?? "";
    row[c[1]] = /t="s"/.test(c[2]) ? strings[+v] : unescape(v);
  }
  return row;
});

const header = rows.shift();
const col = (name) => {
  const key = Object.keys(header).find((k) => header[k] === name);
  if (!key) throw new Error(`column ${name} not found`);
  return key;
};
const [nameMn, pcode, aimagPcode, version] = ["adm2_name1", "adm2_pcode", "adm1_pcode", "version"].map(col);

const soums = rows
  .filter((r) => r[aimagPcode] !== "MN11") // Ulaanbaatar's 9 districts live in divisions.ts
  .map((r) => {
    if (!/^MN\d{4}$/.test(r[pcode]) || !r[pcode].startsWith(r[aimagPcode])) throw new Error(`bad P-code ${r[pcode]}`);
    if (!/^[А-Яа-яЁёӨөҮү -]+$/.test(r[nameMn])) throw new Error(`unexpected characters in ${r[nameMn]}`);
    return [r[pcode].slice(2), r[nameMn]];
  })
  .sort((a, b) => a[0].localeCompare(b[0]));

if (soums.length !== 330) throw new Error(`expected 330 soums, got ${soums.length}`);

writeFileSync(
  new URL("../src/soums.data.ts", import.meta.url),
  `// GENERATED by scripts/build-soums.mjs. Do not edit by hand.
// Source: OCHA COD-AB Mongolia ${rows[0][version]}, sheet mng_admin2 (https://data.humdata.org/dataset/cod-ab-mng)
// Original source: National Statistical Office of Mongolia. Licence: CC BY-IGO.
// [code, Mongolian name]. The OCHA P-code is "MN" + code; the first two digits are the aimag code.
export const SOUM_ROWS: [code: string, nameMn: string][] = [
${soums.map((s) => `  ${JSON.stringify(s)},`).join("\n")}
];
`,
);
console.log(`wrote ${soums.length} soums`);
